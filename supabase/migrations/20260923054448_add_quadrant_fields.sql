-- Cloud-synced Eisenhower quadrant fields for todos and recurrence rules.

alter table public.todos
  add column if not exists quadrant text not null default 'q1',
  add column if not exists quadrant_order integer;

update public.todos
set quadrant = 'q1'
where quadrant is null or quadrant not in ('q1', 'q2', 'q3', 'q4');

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'todos_quadrant_check'
      and conrelid = 'public.todos'::regclass
  ) then
    alter table public.todos
      add constraint todos_quadrant_check
      check (quadrant in ('q1', 'q2', 'q3', 'q4'));
  end if;
end
$$;

create index if not exists todos_quadrant_order_idx
  on public.todos (date, quadrant, quadrant_order);

comment on column public.todos.quadrant is
  'Eisenhower quadrant: q1 important/urgent, q2 important/not urgent, q3 urgent/not important, q4 neither';

comment on column public.todos.quadrant_order is
  'Zero-based task order within a date and quadrant';

alter table public.recurrence_rules
  add column if not exists quadrant text not null default 'q1';

update public.recurrence_rules
set quadrant = 'q1'
where quadrant is null or quadrant not in ('q1', 'q2', 'q3', 'q4');

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'recurrence_rules_quadrant_check'
      and conrelid = 'public.recurrence_rules'::regclass
  ) then
    alter table public.recurrence_rules
      add constraint recurrence_rules_quadrant_check
      check (quadrant in ('q1', 'q2', 'q3', 'q4'));
  end if;
end
$$;

comment on column public.recurrence_rules.quadrant is
  'Default Eisenhower quadrant for todos generated by this recurrence rule';
